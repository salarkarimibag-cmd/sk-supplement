async function main() {
  await connectToDatabase();

  let count = 0;
  for (const post of posts) {
    await BlogPostModel.findOneAndUpdate({ slug: post.slug }, post, {
      upsert: true,
      setDefaultsOnInsert: true,
    });
    count++;
  }

  console.log(`Seeded ${count} blog posts.`);
  process.exit(0);
}

main().catch((error) => {
  console.error("Seed failed:", error);
  process.exit(1);
});
